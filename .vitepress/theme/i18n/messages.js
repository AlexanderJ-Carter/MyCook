export function counterpartPath(path) {
    const n =
        String(path || '/')
            .replace(/\.html$/i, '')
            .replace(/\/index$/i, '')
            .replace(/\/$/, '') || '/';
    return localeRoutes[n] ?? (n === '/en' || n.startsWith('/en/') ? '/' : '/en/');
}
